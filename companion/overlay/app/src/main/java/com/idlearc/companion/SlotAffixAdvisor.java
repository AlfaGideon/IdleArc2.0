    /**
     * Определяет тип слота предмета по распознанному OCR-тексту карточки предмета / Кузницы.
     * Возвращает null, если тип слота по тексту однозначно не распознан.
     */
    public static GearSlot detectSlotFromLines(List<String> lines) {
        if (lines == null || lines.isEmpty()) return null;
        StringBuilder sb = new StringBuilder();
        // Первые строки модалки содержат название предмета и подтип слота — даём им приоритет
        for (int i = 0; i < Math.min(lines.size(), 8); i++) {
            sb.append(lines.get(i)).append(' ');
        }
        String head = DruidKnowledgeBase.normalizeForMatch(sb.toString());

        StringBuilder fullSb = new StringBuilder();
        for (String l : lines) fullSb.append(l).append(' ');
        String all = DruidKnowledgeBase.normalizeForMatch(fullSb.toString());

        if (head.contains("талисман") || all.contains("сила атаки талисмана") || all.contains("бонусы жертв")) {
            return GearSlot.TALISMAN;
        }
        if (head.contains("факел") || all.contains("второй руки") || all.contains("жажды крови")) {
            return GearSlot.TORCH;
        }
        if (head.contains("посох") || head.contains("палочк") || head.contains("когти")
                || head.contains("книга заклинаний") || head.contains("клинок") || head.contains("меч")
                || head.contains("лук") || head.contains("арбалет") || head.contains("коса")
                || head.contains("двуручн") || head.contains("оружие")) {
            return GearSlot.WEAPON;
        }
        if (head.contains("перчатк") || head.contains("обмотк") || head.contains("хватк") || head.contains("рукавиц")) {
            return GearSlot.GLOVES;
        }
        if (head.contains("сапог") || head.contains("ботинк") || head.contains("сандал") || head.contains("быстрого шага")) {
            return GearSlot.BOOTS;
        }
        if (head.contains("пояс") || head.contains("ремен")) {
            return GearSlot.BELT;
        }
        if (head.contains("амулет") || head.contains("ожерел") || head.contains("кулон")) {
            return GearSlot.AMULET;
        }
        if (head.contains("кольц") || head.contains("перстен")) {
            return GearSlot.RING;
        }
        if (head.contains("шлем") || head.contains("капюшон") || head.contains("корона")
                || head.contains("диадем") || head.contains("шапк") || head.contains("тыкв")) {
            return GearSlot.HELMET;
        }
        if (head.contains("брон") || head.contains("кирас") || head.contains("доспех")
                || head.contains("нагруд") || head.contains("жилет") || head.contains("манти") || head.contains("шкура")) {
            return GearSlot.CHEST;
        }
        if (all.contains("осколки питомцев") || all.contains("особый бонус") || all.contains("слияние")) {
            return GearSlot.PET;
        }
        return null;
    }

    /**
     * Формирует подробную карточку рекомендаций по конкретному слоту:
     * 1) Лучшая база предмета
     * 2) Какие 4-5 аффиксов ловить под выбранный режим (Пуш/Босс vs Фарм)
     * 3) Какой именно аффикс ставить под ★ ПРОБУЖДЕНИЕ / ПЕРЕРОЖДЕНИЕ на ЭТОМ слоте (и почему!)
     * 4) Какой Бонус добычи (Смена типа / Трансмутация) и Самоцвет ставить
     */
    public static String formatSlotGuide(GearSlot slot, DruidProfile p) {
        boolean isFarm = (p.mode == DruidProfile.BuildMode.FARM);
        StringBuilder sb = new StringBuilder();

        sb.append(slot.shortChip).append(" — ").append(slot.slotTitle.toUpperCase(Locale.ROOT)).append("\n");
        sb.append("🏆 Лучшая база Друида: ").append(slot.bestBaseRu).append("\n\n");

        sb.append("🌟 КАКОЙ АФФИКС СТАВИТЬ ПОД ПЕРЕРОЖДЕНИЕ / ПРОБУЖДЕНИЕ (★):\n");
        sb.append("👉 ").append(slot.awakenHeadline).append("\n");
        sb.append("• ").append(slot.awakenDetails).append("\n");
        sb.append("• ⚠️ Правило Кузницы: пробуждённый (★) аффикс блокируется от смены! Сначала докрути нужные аффиксы в слотах (закрепив топ-роллы Камнем якоря), и ТОЛЬКО ПОТОМ жми «Перераспределить Пробуждение».\n\n");

        sb.append(isFarm
                ? "💎 ИДЕАЛЬНЫЕ АФФИКСЫ НА ЭТОМ СЛОТЕ (РЕЖИМ ФАРМА):\n"
                : "⚔️ ИДЕАЛЬНЫЕ АФФИКСЫ НА ЭТОМ СЛОТЕ (БОЙ / ПУШ / БОСС):\n");
        String[] list = isFarm ? slot.farmAffixes : slot.combatAffixes;
        for (String a : list) {
            sb.append("  ").append(a).append("\n");
        }

        sb.append("\n🔄 БОНУС ДОБЫЧИ (СМЕНА ТИПА / ТРАНСМУТАЦИЯ):\n  ")
          .append(slot.dropBonusAdvice);
        return sb.toString();
    }

    /**
     * Сверяет распознанные OCR-строки открытого предмета с эталоном ИМЕННО ЕГО СЛОТА
     * и говорит: какие аффиксы оставить, какие перебросить, и куда положить ★ Перерождение!
     */
    public static String buildScannedItemSlotAdvice(GearSlot slot, List<String> lines, DruidProfile p) {
        if (slot == null) {
            return "\n💡 Совет по ★ Пробуждению / Перерождению:\n"
                 + "• На Оружии, Факеле, Перчатках, Амулете и Кольцах гони ★ в «Урон питомца %» или «Шанс двойного удара %».\n"
                 + "• На Шлеме, Броне, Поясе и Сапогах (где нет оружейных проков) гони ★ в «Интеллект» (для DPS) или «Макс. HP %» — НИКОГДА не оставляй ★ на Уклонении (уже 131.7% > 95%) или +% Уроне атаки!";
        }

        StringBuilder full = new StringBuilder();
        for (String l : lines) full.append(l).append(' ');
        String low = DruidKnowledgeBase.normalizeForMatch(full.toString());

        List<String> keep = new ArrayList<>();
        List<String> reroll = new ArrayList<>();
        String bestAwakenHere = null;

        boolean hasPetDmg = low.contains("урон питомц") || low.contains("урона питомц") || low.contains("спутника");
        boolean hasDoubleHit = low.contains("двойного удара") || low.contains("двойной удар");
        boolean hasDoubleDmg = low.contains("двойного урона") || low.contains("двойной урон");
        boolean hasInt = low.contains("интеллект");
        boolean hasCrit = low.contains("шанс крит") || low.contains("крит. урон") || low.contains("крит урон");
        boolean hasMaxHp = low.contains("макс. здоров") || low.contains("макс здоров") || low.contains("крепости");
        boolean hasDr = low.contains("снижение урона") || low.contains("получаемого урона") || low.contains("оберега");
        boolean hasDodge = low.contains("уклонен");
        boolean hasPctAtk = (low.contains("урон атаки") || low.contains("свиреп")) && full.toString().contains("%");
        boolean hasRetal = low.contains("возмезд") || low.contains("отражающ") || low.contains("шанс блока");
        boolean hasStr = low.contains("сила") && !low.contains("талисман");
        boolean hasGoldExp = low.contains("золот") || low.contains("опыт") || low.contains("богатств");

        boolean offensiveSlot = (slot == GearSlot.WEAPON || slot == GearSlot.TORCH
                || slot == GearSlot.GLOVES || slot == GearSlot.AMULET || slot == GearSlot.RING);

        if (hasPetDmg) {
            keep.add("Урон питомца % (закрепи!)");
            bestAwakenHere = "Урон питомца %";
        }
        if (hasDoubleHit) {
            keep.add("Шанс двойного удара % (закрепи!)");
            if (bestAwakenHere == null) bestAwakenHere = "Шанс двойного удара %";
        }
        if (hasDoubleDmg) {
            keep.add("Шанс двойного урона %");
            if (bestAwakenHere == null && offensiveSlot) bestAwakenHere = "Шанс двойного урона %";
        }
        if (hasInt) {
            keep.add("Интеллект");
            if (bestAwakenHere == null && !offensiveSlot) bestAwakenHere = "Интеллект";
        }
        if (!offensiveSlot && hasDr) {
            if (p.damageReductionRaw < 95.5) keep.add("Снижение урона % (держит кап 95%)");
            else reroll.add("Снижение урона % (если и без этой вещи остаётся 95%)");
        }
        if (!offensiveSlot && hasMaxHp) {
            keep.add("Макс. здоровье %");
            if (bestAwakenHere == null) bestAwakenHere = "Макс. здоровье %";
        }
        if (hasCrit) {
            keep.add("Крит (но под ★ слабее Двойного удара)");
        }
        if (p.mode == DruidProfile.BuildMode.FARM && hasGoldExp) {
            keep.add("Золото / Опыт % (отлично для Фарма)");
            if (bestAwakenHere == null) bestAwakenHere = "Золото % / Опыт %";
        }

        if (hasDodge && p.dodgeRaw >= 95.0) {
            reroll.add("Уклонение -> В ПЕРЕБРОС (оверкап " + String.format(Locale.US, "%.1f%% > 95%%", p.dodgeRaw) + ", 0% пользы!)");
        }
        if (hasPctAtk) {
            reroll.add("+% Урон атаки / Свирепый -> В ПЕРЕБРОС / Смену типа в «Спутника» (не работает на пета!)");
        }
        if (hasRetal) {
            reroll.add("Возмездие / Блок / Отражающий -> В ПЕРЕБРОС / Смену типа в «Спутника»!");
        }
        if (hasStr) {
            reroll.add("Сила -> В ПЕРЕБРОС (мёртвый стат для Друида)");
        }

        StringBuilder out = new StringBuilder();
        out.append("\n━━ ПОДБОР ПОД СЛОТ: ").append(slot.shortChip).append(" (").append(slot.slotTitle).append(") ━━\n");
        out.append("🌟 Куда ставить ★ Перерождение/Пробуждение на этом слоте:\n   👉 ").append(slot.awakenHeadline).append("\n");
        if (bestAwakenHere != null) {
            out.append("   ✅ Из уже выбитых на этой вещи лучший кандидат под ★: «").append(bestAwakenHere).append("»!\n");
        } else if (offensiveSlot) {
            out.append("   ⚠️ На этой вещи пока НЕТ ни «Урона питомца %», ни «Двойного удара %» — сначала выбей их в аффиксах, прежде чем ловить ★!\n");
        } else {
            out.append("   ⚠️ Для этого слота сначала выбей «Интеллект» (под DPS) или «Макс. HP %», и только потом кидай на него ★!\n");
        }

        if (!keep.isEmpty()) {
            out.append("✅ Оставить / Закрепить: ").append(joinList(keep)).append("\n");
        }
        if (!reroll.isEmpty()) {
            out.append("🔄 Срочно заменить: ").append(joinList(reroll)).append("\n");
        }

        out.append("\nЭталон топ-аффиксов для «").append(slot.slotTitle).append("»:\n");
        String[] targetList = (p.mode == DruidProfile.BuildMode.FARM) ? slot.farmAffixes : slot.combatAffixes;
        for (int i = 0; i < Math.min(4, targetList.length); i++) {
            out.append("  ").append(targetList[i]).append("\n");
        }
        out.append("🔄 Бонус добычи: ").append(slot.dropBonusAdvice);
        return out.toString();
    }

    private static String joinList(List<String> items) {
        StringBuilder sb = new StringBuilder();
        for (int i = 0; i < items.size(); i++) {
            if (i > 0) sb.append("; ");
            sb.append(items.get(i));
        }
        return sb.toString();
    }
